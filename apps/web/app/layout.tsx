import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import { ThemeProvider } from "@/components/theme-provider";

const geistSans = Geist({ variable: "--font-geist-sans", subsets: ["latin"] });
const geistMono = Geist_Mono({ variable: "--font-geist-mono", subsets: ["latin"] });

export const metadata: Metadata = {
  title: "Retainer — recurring USDC billing on Base spend permissions",
  description:
    "Non-custodial recurring and usage-based USDC billing. Customer to router to merchant in one atomic transaction, on Base spend permissions.",
};

// Root layout carries only what every route shares: fonts and the theme
// provider. Chrome lives in the route groups -- (site) has the marketing nav
// and footer, dashboard has its own application shell -- so each can change
// without touching the other.
export default function RootLayout({ children }: Readonly<{ children: React.ReactNode }>) {
  return (
    <html lang="en" suppressHydrationWarning>
      <body className={`${geistSans.variable} ${geistMono.variable} antialiased`}>
        <ThemeProvider attribute="class" defaultTheme="system" enableSystem disableTransitionOnChange>
          {children}
        </ThemeProvider>
      </body>
    </html>
  );
}
